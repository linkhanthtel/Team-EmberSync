import { motion } from 'framer-motion'
import { Check, Copy, RefreshCw, Sparkles, Square } from 'lucide-react'
import { useState } from 'react'
import type { AiMode } from '../lib/types.ts'
import { Markdown } from './Markdown.tsx'

export function AiBriefing({
  text,
  busy,
  error,
  usedMode,
  scopeCount,
  model,
  onGenerate,
  onStop,
}: {
  text: string
  busy: boolean
  error: string | null
  usedMode: AiMode | null
  scopeCount: number
  model?: string
  onGenerate: () => void
  onStop: () => void
}) {
  const [copied, setCopied] = useState(false)
  const empty = !text && !busy && !error

  return (
    <section data-busy={busy} className="ai-ring card flex flex-col min-h-[420px] max-h-[640px] overflow-hidden">
      <header className="flex items-center justify-between gap-2 px-5 pt-5 pb-3">
        <div className="flex items-center gap-2.5">
          <div className="size-8 rounded-lg bg-gradient-to-br from-ember via-ember-2 to-ai grid place-items-center shadow-lg shadow-ember/20">
            <Sparkles className="size-4 text-black" />
          </div>
          <div>
            <h3 className="text-sm font-semibold ai-text">AI Briefing</h3>
            <p className="text-[11px] text-muted">
              Scope: <span className="tabular text-ink-2">{scopeCount}</span> filtered events
            </p>
          </div>
        </div>
        <div className="flex items-center gap-1">
          {text && !busy && (
            <button
              title="Copy"
              onClick={() => {
                navigator.clipboard?.writeText(text)
                setCopied(true)
                setTimeout(() => setCopied(false), 1500)
              }}
              className="p-2 rounded-md text-muted hover:text-ink hover:bg-white/5"
            >
              {copied ? <Check className="size-4 text-[#0ca30c]" /> : <Copy className="size-4" />}
            </button>
          )}
          {busy ? (
            <button onClick={onStop} className="inline-flex items-center gap-1.5 rounded-lg border border-line px-3 py-1.5 text-xs text-ink-2 hover:bg-white/5">
              <Square className="size-3 fill-current" /> Stop
            </button>
          ) : (
            !empty && (
              <button onClick={onGenerate} className="inline-flex items-center gap-1.5 rounded-lg border border-line px-3 py-1.5 text-xs text-ink-2 hover:bg-white/5">
                <RefreshCw className="size-3" /> Regenerate
              </button>
            )
          )}
        </div>
      </header>

      <div className="flex-1 overflow-y-auto px-5 pb-5">
        {empty && (
          <div className="h-full flex flex-col items-center justify-center text-center gap-4 py-8">
            <motion.div
              animate={{ rotate: [0, 8, -8, 0], scale: [1, 1.05, 1] }}
              transition={{ duration: 4, repeat: Infinity }}
              className="size-14 rounded-2xl bg-gradient-to-br from-ember/20 to-ai/20 border border-line grid place-items-center"
            >
              <Sparkles className="size-6 text-ember-2" />
            </motion.div>
            <div>
              <p className="text-sm text-ink">Get an instant briefing</p>
              <p className="text-xs text-muted mt-1 max-w-56">Claude analyzes the events in your current filters: trends, hotspots, risks and next steps.</p>
            </div>
            <button
              onClick={onGenerate}
              disabled={!scopeCount}
              className="inline-flex items-center gap-2 rounded-lg bg-gradient-to-r from-ember to-ember-2 px-4 py-2 text-sm font-medium text-black shadow-lg shadow-ember/25 hover:brightness-110 disabled:opacity-40"
            >
              <Sparkles className="size-4" /> Generate briefing
            </button>
          </div>
        )}

        {busy && !text && (
          <div className="space-y-3 pt-2">
            <div className="text-xs ai-text font-medium">Analyzing {scopeCount} events…</div>
            {[40, 95, 88, 70, 30, 92, 85, 60].map((w, i) => (
              <div key={i} className="shimmer h-3 rounded" style={{ width: `${w}%`, animationDelay: `${i * 80}ms` }} />
            ))}
          </div>
        )}

        {text && <Markdown text={text} streaming={busy} />}
        {error && <p className="text-sm text-[#ff8a8d] mt-3">{error}</p>}
      </div>

      {usedMode && (text || busy) && (
        <footer className="px-5 py-2.5 border-t border-line text-[11px] text-muted flex items-center gap-1.5">
          <span className={`size-1.5 rounded-full ${usedMode === 'live' ? 'bg-[#0ca30c]' : 'bg-muted'}`} />
          {usedMode === 'live' ? `Generated by ${model ?? 'Claude'}` : 'Demo mode · templated summary'}
        </footer>
      )}
    </section>
  )
}
